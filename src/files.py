"""The files Trellis reads and writes.

A defconfig holds the user's choices in the Linux format, one per line:
``CONFIG_NAME=y``, ``CONFIG_NAME="text"``, ``CONFIG_NAME=16`` or
``# CONFIG_NAME is not set``. It is meant for version control.

``config.pyb`` holds the resolved configuration as one PyBonsai
dictionary named ``options``, generated and never edited. A bool option
is True or False, a tristate option ``"y"``, ``"m"`` or ``"n"``, an int
or hex option a number and a string option a string.
"""

from __future__ import annotations

import ast
import json
import os
import re
import tempfile
from collections.abc import Iterable, Mapping
from pathlib import Path

from .errors import InvalidValue
from .models import Assignment, Configuration, OptionTree

PREFIX = "CONFIG_"

_SET = re.compile(r"^CONFIG_([A-Za-z0-9_]+)=(.*)$")
_UNSET = re.compile(r"^# CONFIG_([A-Za-z0-9_]+) is not set$")


def read_defconfig(text: str, file: str = "defconfig") -> list[Assignment]:
    """Return the choices in defconfig text, in the order written."""
    choices: dict[str, Assignment] = {}
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if match := _UNSET.match(line):
            choices[match[1]] = Assignment(symbol=match[1], value="n")
        elif match := _SET.match(line):
            choices[match[1]] = Assignment(symbol=match[1], value=_unquote(match[2], file, number))
        elif line and not line.startswith("#"):
            raise InvalidValue(f"{file}:{number}: not a CONFIG_ line")
    return list(choices.values())


def _unquote(value: str, file: str, number: int) -> str:
    if not value.startswith('"'):
        return value
    if len(value) < 2 or not value.endswith('"'):
        raise InvalidValue(f"{file}:{number}: unterminated string")
    out: list[str] = []
    escaped = False
    for char in value[1:-1]:
        if escaped or char != "\\":
            out.append(char)
            escaped = False
        else:
            escaped = True
    return "".join(out)


def write_defconfig(choices: Iterable[Assignment], tree: OptionTree) -> str:
    """Defconfig text for ``choices``, in the order of the tree."""
    order = {name: i for i, name in enumerate(tree.symbols)}
    lines: list[str] = []
    for choice in sorted(choices, key=lambda c: order.get(c.symbol, len(order))):
        kind = tree.symbols[choice.symbol].type if choice.symbol in tree.symbols else "string"
        if kind in ("bool", "tristate") and choice.value == "n":
            lines.append(f"# {PREFIX}{choice.symbol} is not set")
        elif kind == "string":
            text = choice.value.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'{PREFIX}{choice.symbol}="{text}"')
        else:
            lines.append(f"{PREFIX}{choice.symbol}={choice.value}")
    return "".join(line + "\n" for line in lines)


def write_config(configuration: Configuration, tree: OptionTree) -> str:
    """Return the text of ``config.pyb`` for a resolved configuration."""
    title = json.dumps(tree.title)
    lines = [
        f"# Generated by trellis from the option tree {title}. Do not edit:",
        "# change the defconfig and run trellis olddefconfig.",
        "",
        "options = {",
    ]
    for name, value in configuration.values.items():
        lines.append(f"    {json.dumps(name)}: {_python(tree.symbols[name].type, value)},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _python(kind: str, value: str) -> str:
    if kind == "bool":
        return "True" if value == "y" else "False"
    if kind == "int":
        return str(int(value, 10))
    if kind == "hex":
        return f"0x{int(value, 16):x}"
    return json.dumps(value)


def read_config(text: str, tree: OptionTree) -> dict[str, str]:
    """Return the values in ``config.pyb`` text, in Kconfig form, for options still in ``tree``."""
    try:
        module = ast.parse(text)
    except SyntaxError as error:
        raise InvalidValue(f"config.pyb cannot be read: {error}") from None
    for node in module.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "options"
        ):
            try:
                options = ast.literal_eval(node.value)
            except ValueError:
                break
            if isinstance(options, dict):
                return _kconfig_values(options, tree)
    raise InvalidValue("config.pyb has no options dictionary")


def _kconfig_values(options: Mapping[object, object], tree: OptionTree) -> dict[str, str]:
    values: dict[str, str] = {}
    for name, value in options.items():
        if not isinstance(name, str) or name not in tree.symbols:
            continue
        kind = tree.symbols[name].type
        if isinstance(value, bool):
            values[name] = "y" if value else "n"
        elif isinstance(value, int):
            values[name] = f"0x{value:x}" if kind == "hex" else str(value)
        else:
            values[name] = str(value)
    return values


def write_file(path: str | Path, text: str) -> None:
    """Replace ``path`` with ``text`` in one step, so a reader sees one or the other."""
    target = Path(path)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{target.name}.", dir=target.parent)
    try:
        mode = target.stat().st_mode & 0o777 if target.exists() else 0o644
        os.fchmod(descriptor, mode)
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(text)
        os.replace(temporary, target)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


